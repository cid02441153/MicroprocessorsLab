	myArray EQU 0x400	; Address in RAM for data
	counter EQU 0x20	; Address of counter variable
	align	2		; ensure alignment of subsequent instructions 
	; ******* Main programme *********************
start:
	
	lfsr	0, myArray	; Load FSR0 with address in RAM	
	movlw	low highword(myTable)	; address of data in PM
	movwf	TBLPTRU, A	; load upper bits to TBLPTRU
	movlw	high(myTable)	; address of data in PM
	movwf	TBLPTRH, A	; load high byte to TBLPTRH
	movlw	low(myTable)	; address of data in PM
	movwf	TBLPTRL, A	; load low byte to TBLPTRL
	movlw	256		; 22 bytes to read
	movwf 	counter, A	; our counter register
loop:
        tblrd*+			; move one byte from PM to TABLAT, increment TBLPRT
	movff	TABLAT, POSTINC0	; move read data from TABLAT to (FSR0), increment FSR0	
	movff	TABLAT, PORTJ
	
	
	movlw	0x00
	movwf	PORTD, A
	
	movlw	0x01
	movwf	PORTD, A
	
	; ******* Define large number for delay *******
	movlw low highword(0x00FFFF)
	movwf 0x12, A
	movlw high(0x00FFFF) 
	movwf 0x11, A 
	movlw low(0x00FFFF)
	movwf 0x10, A 
	call Delay
	decfsz	counter, A	; count down to zero
	bra	loop		; keep going until finished
	
    goto	0
	
; ******* Delay Subroutine *******
Delay: 
    movlw 0x00 ;move literal 0 to working reg
Dloop: 
    decf 0x10, f, A ; decrements lower byte by 0x11
    subwfb 0x11, f, A
    subwfb 0x12, f, A ; subtract w and borrow from f
    bc Dloop ; if carry bit, loop again
    return	
	

	end	main
